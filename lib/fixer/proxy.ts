import type { Framework, SourceFile } from "../types";

// Server-side proxies for AI providers. When an AI key was found in browser
// code, the browser calls this route instead and the key stays on the server.
// We only generate proxies for AI APIs with a narrow allow-list of endpoints:
// a blind proxy for Stripe or AWS would let any visitor do anything with the key.

export interface ProxyProvider {
  slug: string;
  name: string;
  upstream: string;
  allowedPaths: string[];
  authHeaders: (keyExpr: string) => string;
  examplePath: string;
}

